def words_from(text):
    """Слова с тайм-кодами; между строками — пауза, как в живой речи."""
    ws, t = [], 0.35
    for line in text.strip().split('\n'):
        for w in line.split():
            dur = max(0.22, len(w) * 0.062)
            ws.append({'w': w, 's': round(t, 3), 'e': round(t + dur, 3)})
            t += dur + 0.075
        t += 0.45
    return ws, t + 0.4

bad = 0
for name, txt in SCRIPTS.items():
    ws, dur = words_from(txt)
    pl, _subs = P.build(ws, BRAND, tail=2.0)
    sc = pl['scenes']
    print('\n=== %s  (%.1f с, %d сцен)' % (name, dur, len(sc)))
    for s in sc:
        print('   %-9s %6.2f–%6.2f  %.1fс' % (s['n'], s['s'], s['e'], s['e'] - s['s']))
